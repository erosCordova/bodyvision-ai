"""An independent PostgreSQL restore must preserve every row and sequence."""

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location(
    "restored_data", ROOT / "scripts/verify_restored_data.py"
)
restored = importlib.util.module_from_spec(spec)
spec.loader.exec_module(restored)


class RestoredDataTests(unittest.TestCase):
    def setUp(self):
        work = tempfile.TemporaryDirectory()
        self.addCleanup(work.cleanup)
        self.original = Path(work.name) / "original.sql"
        self.rebuilt = Path(work.name) / "rebuilt.sql"

    def sample(self, rows, sequence=7):
        return (
            b"-- Database dump generated by pg_dump\n"
            b"\\restrict random-id\n"
            b"SET row_security = off;\n"
            b"COPY public.profiles (id, name) FROM stdin;\n"
            + b"".join(row + b"\n" for row in rows)
            + b"\\.\n"
            + b"SELECT pg_catalog.setval('public.profile_seq', "
            + str(sequence).encode()
            + b", true);\n"
            + b"\\unrestrict random-id\n"
        )

    def compare(self, left, right):
        self.original.write_bytes(left)
        self.rebuilt.write_bytes(right)
        return restored.fingerprint(self.original) == restored.fingerprint(self.rebuilt)

    def test_reordering_rows_and_dump_metadata_is_allowed(self):
        a = self.sample([b"1\tA", b"2\tB", b"2\tB"])
        b = self.sample([b"2\tB", b"1\tA", b"2\tB"]).replace(
            b"random-id", b"another-id"
        )
        self.assertTrue(self.compare(a, b))

    def test_changed_deleted_extra_or_duplicate_row_is_rejected(self):
        original = self.sample([b"1\tA", b"2\tB", b"2\tB"])
        for changed in (
            [b"1\tA", b"2\tC", b"2\tB"],
            [b"1\tA", b"2\tB"],
            [b"1\tA", b"2\tB", b"2\tB", b"2\tB"],
            [b"1\tA", b"1\tA", b"2\tB"],
        ):
            with self.subTest(changed=changed):
                self.assertFalse(self.compare(original, self.sample(changed)))

    def test_sequence_and_copy_header_differences_are_rejected(self):
        base = self.sample([b"1\tA", b"2\tB"])
        self.assertFalse(self.compare(base, self.sample([b"1\tA", b"2\tB"], 8)))
        self.assertFalse(
            self.compare(
                base,
                base.replace(b"COPY public.profiles", b"COPY public.other_table"),
            )
        )
        self.assertFalse(
            self.compare(base, base.replace(b"(id, name)", b"(name, id)"))
        )

    def test_missing_or_incomplete_sections_are_rejected(self):
        for broken in (
            b"",
            b"-- no data\n",
            b"COPY public.profiles (id) FROM stdin;\n1\n",
            b"COPY public.profiles (id) FROM stdout;\n1\n\\.\n",
            b"COPY public.profiles (id) FROM stdin;\n1\n\\.\n"
            b"COPY public.profiles (id) FROM stdin;\n1\n\\.\n",
        ):
            self.original.write_bytes(broken)
            with self.subTest(broken=broken[:40]):
                with self.assertRaises(restored.RestoredDataRejected):
                    restored.fingerprint(self.original)

    def test_cli_never_prints_records_or_file_paths_on_failure(self):
        self.original.write_bytes(self.sample([b"secret_fake_value"]))
        self.rebuilt.write_bytes(self.sample([b"another_fake_value"]))
        with patch("builtins.print") as messages:
            self.assertEqual(
                restored.main([str(self.original), str(self.rebuilt)]), 1
            )
        result = messages.call_args.args[0]
        self.assertEqual(json.loads(result)["event"], "synthetic_recovery_data_mismatch")
        self.assertEqual(json.loads(result)["different_tables"], ["public.profiles"])
        self.assertNotIn("secret_fake_value", result)
        self.assertNotIn("another_fake_value", result)

    def test_sql_injection_like_commands_are_rejected(self):
        self.original.write_bytes(
            self.sample([b"1\tA"]) + b"DROP TABLE public.profiles;\n"
        )
        with self.assertRaises(restored.RestoredDataRejected):
            restored.fingerprint(self.original)


if __name__ == "__main__":
    unittest.main()
